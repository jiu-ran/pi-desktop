#!/usr/bin/env node
// 生成 / 使用 Pi Desktop 的更新签名密钥（ed25519）。
//
// 背景：CI 发布时会用私钥给 SHA256SUMS.txt 签名（生成 SHA256SUMS.txt.sig），
// 客户端内置公钥，下载安装包时先验签再用清单里的 SHA-256 比对附件。没有这一步，
// 「更新」就等于「无条件执行 GitHub 上的附件」——发布账号被盗即可远程执行代码。
//
// 用法：
//   node scripts/gen-update-key.mjs                 生成一对新密钥（打印公钥/私钥）
//   node scripts/gen-update-key.mjs public-key      从私钥推导公钥（私钥取 UPDATE_SIGNING_KEY）
//   node scripts/gen-update-key.mjs sign <file>     给文件签名，输出 <file>.sig
//   node scripts/gen-update-key.mjs emit-go [path]  生成内置公钥的 Go 文件（给 CI 用）
//
// 私钥只放在 GitHub Secret（名字 UPDATE_SIGNING_KEY，内容是 base64 种子）里，不要提交。
// 公钥的两种注入方式：
//   1) 构建时生成 internal/host/update_key_generated.go（CI 用的就是这条）
//   2) go build -ldflags "-X github.com/jiu-ran/pi-desktop/internal/host.updatePublicKeyBase64=<公钥>"

import { createPrivateKey, createPublicKey, generateKeyPairSync, randomBytes, sign } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const PKCS8_PREFIX = Buffer.from("302e020100300506032b657004220420", "hex");
const SPKI_PREFIX = Buffer.from("302a300506032b6570032100", "hex");

function privateKeyFromSeed(seed) {
  if (seed.length !== 32) throw new Error("签名私钥长度不对（应为 32 字节种子）");
  return createPrivateKey({ key: Buffer.concat([PKCS8_PREFIX, seed]), format: "der", type: "pkcs8" });
}

function rawPublicKey(privateKey) {
  const publicKey = createPublicKey(privateKey);
  const spki = publicKey.export({ format: "der", type: "spki" });
  if (!spki.equals(Buffer.concat([SPKI_PREFIX, spki.subarray(spki.length - 32)]))) {
    throw new Error("导出的公钥格式不符合预期");
  }
  return spki.subarray(spki.length - 32);
}

/** 从 UPDATE_SIGNING_KEY（或 --key）取私钥种子。 */
function seedFromEnv() {
  const raw = String(process.env.UPDATE_SIGNING_KEY ?? "").trim();
  if (!raw) throw new Error("没有找到 UPDATE_SIGNING_KEY（私钥种子，base64）");
  const seed = Buffer.from(raw, "base64");
  if (seed.length !== 32) throw new Error("UPDATE_SIGNING_KEY 不是 32 字节 base64 种子");
  return seed;
}

function generate() {
  // 直接生成原始种子：Node 不提供「导出 ed25519 种子」的 API，这里用随机数当种子，
  // 再用它构造 PKCS8 私钥（与 OpenSSL 的 ed25519 raw key 等价）。
  const seed = randomBytes(32);
  const privateKey = privateKeyFromSeed(seed);
  const publicKey = rawPublicKey(privateKey);
  console.log("# 私钥：放进 GitHub Secret，名字 UPDATE_SIGNING_KEY（内容是 base64 种子）");
  console.log(`UPDATE_SIGNING_KEY=${seed.toString("base64")}`);
  console.log("");
  console.log("# 公钥（内置进客户端，见文件头的两种注入方式）");
  console.log(`UPDATE_PUBLIC_KEY=${publicKey.toString("base64")}`);
  console.log("");
  console.log("# 注意：私钥只留在 CI secret 里；换密钥意味着旧版本客户端要升级后才会信任新签名。");
  // 顺手校验一次往返，防止生成出来的密钥对不可用。
  const probe = sign(null, Buffer.from("pi-desktop"), privateKey);
  if (probe.length !== 64) throw new Error("生成的密钥不可用");
}

function publicKey() {
  console.log(rawPublicKey(privateKeyFromSeed(seedFromEnv())).toString("base64"));
}

function signFile(file) {
  if (!file) throw new Error("用法：node scripts/gen-update-key.mjs sign <file>");
  const signature = sign(null, readFileSync(file), privateKeyFromSeed(seedFromEnv()));
  const target = `${file}.sig`;
  writeFileSync(target, signature);
  console.log(`已生成签名：${target}（${signature.length} 字节）`);
}

/** CI 用：把公钥写成 Go 文件，避免依赖 mygo build 是否透传 -ldflags。 */
function emitGo(target) {
  const path = target || "internal/host/update_key_generated.go";
  const key = rawPublicKey(privateKeyFromSeed(seedFromEnv())).toString("base64");
  const source = [
    "// Code generated by scripts/gen-update-key.mjs; DO NOT EDIT.",
    "",
    "package host",
    "",
    "// 发布签名公钥：由 CI 在构建前写入（见 .github/workflows/build.yml）。",
    "// 用 -ldflags -X 注入时这里不覆盖（链接器在 init 之前就写好了变量）。",
    "func init() {",
    "\tif updatePublicKeyBase64 == \"\" {",
    `\t\tupdatePublicKeyBase64 = ${JSON.stringify(key)}`,
    "\t}",
    "}",
    "",
  ].join("\n");
  writeFileSync(path, source);
  console.log(`已写入 ${path}`);
}

const [command = "generate", ...rest] = process.argv.slice(2);
try {
  switch (command) {
    case "generate":
      generate();
      break;
    case "public-key":
      publicKey();
      break;
    case "sign":
      signFile(rest[0]);
      break;
    case "emit-go":
      emitGo(rest[0]);
      break;
    default:
      throw new Error(`未知命令：${command}`);
  }
} catch (error) {
  console.error(`[gen-update-key] ${error?.message ?? error}`);
  process.exit(1);
}
